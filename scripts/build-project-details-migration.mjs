// Builds the latest project-details migration (never edit one already applied; bump the folder name) from
// lib/portfolio-doc-projects.js. Existing rows keep their cover, emoji, colour, order and
// published state; missing rows are created.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const source = readFileSync(new URL('../lib/portfolio-doc-projects.js', import.meta.url), 'utf8');
const docProjects = new Function(`${source.replace('export const', 'const')}; return docProjects;`)();

const str = (v) => (v == null || v === '' ? 'NULL' : `$q$${v}$q$`);
const arr = (a) => (a.length ? `ARRAY[${a.map((v) => `$q$${v}$q$`).join(', ')}]::text[]` : 'ARRAY[]::text[]');

const only = process.argv[2] ? process.argv[2].split(',') : null;
const rows = docProjects.filter((p) => !only || only.includes(p.slug)).map((p) => `INSERT INTO "Game" ("id","slug","title","description","tag","categories","tech","year","emoji","bgColor","published","sortOrder","portfolioSection","projectContext","role","contribution","contributions","team","recognition","features","highlights","platforms","liveUrl","inDevelopment","updatedAt")
VALUES (gen_random_uuid()::text, ${str(p.slug)}, ${str(p.title)}, ${str(p.description)}, ${str(p.tag)}, ${arr(p.categories)}, ${str(p.tech)}, ${str(p.year)}, ${str(p.emoji)}, ${str(p.bgColor)}, true, ${p.sortOrder}, ${str(p.portfolioSection)}, ${str(p.projectContext)}, ${str(p.role)}, ${str(p.contribution)}, ${arr(p.contributions)}, ${arr(p.team)}, ${str(p.recognition)}, ${arr(p.features)}, ${arr(p.highlights)}, ${str(p.platforms)}, ${str(p.liveUrl)}, ${p.inDevelopment}, CURRENT_TIMESTAMP)
ON CONFLICT ("slug") DO UPDATE SET
  "title" = EXCLUDED."title", "description" = EXCLUDED."description", "tag" = EXCLUDED."tag",
  "categories" = EXCLUDED."categories", "tech" = EXCLUDED."tech", "year" = EXCLUDED."year",
  "portfolioSection" = EXCLUDED."portfolioSection", "projectContext" = EXCLUDED."projectContext",
  "role" = EXCLUDED."role", "contribution" = EXCLUDED."contribution", "contributions" = EXCLUDED."contributions",
  "team" = EXCLUDED."team", "recognition" = EXCLUDED."recognition", "features" = EXCLUDED."features",
  "highlights" = EXCLUDED."highlights", "platforms" = EXCLUDED."platforms", "liveUrl" = COALESCE(EXCLUDED."liveUrl", "Game"."liveUrl"),
  "inDevelopment" = EXCLUDED."inDevelopment", "updatedAt" = CURRENT_TIMESTAMP;`);

const dir = new URL('../prisma/migrations/20261025000800_store_links_and_more_projects/', import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL('migration.sql', dir), `-- Project details from Portfolio_Project_Details.docx. Generated by scripts/build-project-details-migration.mjs.\n\n${rows.join('\n\n')}\n`);
console.log(`${rows.length} projects written`);
